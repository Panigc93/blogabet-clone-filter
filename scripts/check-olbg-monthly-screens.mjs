import {chromium} from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'
const js=fs.readFileSync('/tmp/olbg-monthly-preview.js','utf8')
const css=fs.readFileSync(new URL('../app/globals.css',import.meta.url),'utf8')
const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await b.newPage({viewport:{width:1280,height:900}})
await page.route('https://**/*',route=>route.abort())
await page.setContent('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#f5f5f5;font-family:Arial,sans-serif}'+css+'</style><div id="root"></div>')
await page.addScriptTag({content:js})
await page.getByRole('heading').waitFor()
assert.equal(await page.locator('.tipster-block').count(),3)
assert.equal(await page.getByLabel('ROI publicado mínimo',{exact:true}).isDisabled(),true)
await page.screenshot({path:'/downloads/olbg-monthly-desktop.png',fullPage:true})
await page.getByLabel('Mes OLBG',{exact:true}).selectOption('2026-10')
await page.getByLabel('Orden OLBG del mes').selectOption('roi-desc')
assert.match(await page.locator('.tipster-block').last().innerText(),/Sin dato de este mes/)
await page.getByLabel('ROI publicado mínimo',{exact:true}).fill('-17')
await page.waitForTimeout(70)
assert.equal(await page.locator('.tipster-block').count(),1)
assert.match(await page.locator('.tipster-block').innerText(),/Grobler/)
await page.getByLabel('ROI publicado mínimo',{exact:true}).fill('')
await page.getByLabel('Mes OLBG',{exact:true}).selectOption('latest-available')
await page.setViewportSize({width:390,height:844})
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true)
await page.screenshot({path:'/downloads/olbg-monthly-mobile.png',fullPage:true})
await page.getByLabel('Mes OLBG',{exact:true}).selectOption('2026-10')
await page.locator('.tipster-block').filter({hasText:'Grobler'}).locator('summary').click()
await page.screenshot({path:'/downloads/olbg-monthly-history-mobile.png',fullPage:true})
assert.equal(await page.locator('.tipster-block').filter({hasText:'Grobler'}).locator('tbody tr').count(),13)
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true)
await page.getByLabel('Meses con resultados mínimos').selectOption('12')
assert.equal(await page.locator('.tipster-block').count(),2)
await b.close()
console.log('Browser checks passed: latest mode, same-month sorting/filtering, null, month switch, minimum result months, 13 history rows, mobile overflow.')
